package eval

// Case is one evaluation scenario: a natural-language user request and the
// expected tool selection. See eval/RUBRIC.md for the scenario rubric.
type Case struct {
	ID string `json:"id"`
	// UserSays is the raw chat message the user sends to the agent.
	// Must follow the rubric: no tool/service keywords, conversational tone,
	// user-known identifiers only, includes content context when writing.
	UserSays string `json:"user_says"`
	// Context describes the page state the agent would know from reading the
	// page. Grounded in canonical page fixtures (see RUBRIC.md). NOT a hint
	// about which tool to use — it's the world the user lives in.
	Context string `json:"context,omitempty"`
	// Query is the legacy field kept for backward compatibility; new cases
	// should use UserSays + Context instead.
	Query        string `json:"query,omitempty"`
	ExpectedTool string `json:"expected_tool"`
	// AcceptableTools lists additional tool names that count as correct for
	// this case (besides ExpectedTool). Use when the distinction between two
	// tools is an API ergonomics choice invisible at tool-selection time.
	AcceptableTools []string       `json:"acceptable_tools,omitempty"`
	ExpectedArgs    map[string]any `json:"expected_args,omitempty"`
	// ExcludedTool is set for exclusion cases: a tool that must NOT be selected.
	// When set, ExpectedTool may be empty (meaning "select nothing / decline").
	ExcludedTool string   `json:"excluded_tool,omitempty"`
	Services     []string `json:"services"`
	Tags         []string `json:"tags"` // must include difficulty: "easy"/"medium"/"hard"
}

